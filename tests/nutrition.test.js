const assert = require('node:assert/strict');
const { localDate, rollover } = require('../dist/nutrition.js');
assert.equal(localDate(new Date(2026, 9, 13, 0, 1)), '2026-10-13');
const state = { nutritionDate: '2026-10-12', meals: [{name: 'Dinner', calories: 450, protein: 25, carbs: 50, fat: 15}], calories: 450, protein: 25, carbs: 50, fat: 15, settings: { language: 'ja' } };
assert.equal(rollover(state, '2026-10-13'), true);
assert.equal(state.meals.length, 0);
for (const key of ['calories', 'protein', 'carbs', 'fat']) assert.equal(state[key], 0);
assert.equal(state.nutritionHistory['2026-10-12'].meals[0].name, 'Dinner');
assert.equal(state.nutritionHistory['2026-10-12'].calories, 450);
assert.equal(state.settings.language, 'ja');
assert.equal(rollover(state, '2026-10-13'), false);
state.meals.push({name: 'Lunch', calories: 200}); state.calories = 200;
const restored = JSON.parse(JSON.stringify(state));
assert.equal(rollover(restored, '2026-10-20'), true);
assert.equal(restored.nutritionHistory['2026-10-13'].calories, 200);
assert.equal(restored.nutritionHistory['2026-10-12'].calories, 450);
assert.equal(restored.nutritionHistory['2026-10-14'], undefined);
const legacy = { meals: [{name: 'Old meal'}], calories: 100 };
rollover(legacy, '2026-10-13');
assert.equal(legacy.nutritionHistory.undated.meals[0].name, 'Old meal');
assert.equal(legacy.calories, 0);
assert.equal(rollover(legacy, '2026-10-13'), false);
const fresh = { meals: [], calories: 0 };
rollover(fresh, '2026-10-13');
assert.deepEqual(fresh.nutritionHistory, {});
console.log('Local dates, midnight rollover, persistence, skipped days and legacy preservation passed');
